export type ResultatPolice =
  | { ok: true; famille: string; metriques: MetriquesPolice }
  | { ok: false; raison: string };

/**
 * La police d'un calque texte · refus explicite si elle n'est pas embarquée.
 * Jamais de police de repli : un rendu avec d'autres métriques mentirait sur
 * la mise en page validée.
 */
export function policeDuDocument(fonts: Readonly<Record<string, { family: string; assetId: string | null }>>, fontId: string): ResultatPolice {
  const f = Object.prototype.hasOwnProperty.call(fonts, fontId) ? fonts[fontId] : undefined;
  if (!f) return { ok: false, raison: `police « ${fontId} » non déclarée dans le document` };
  if (f.assetId !== null) return { ok: false, raison: `police téléversée « ${f.family} » · rendu non pris en charge (aucune police de repli)` };
  const m = Object.prototype.hasOwnProperty.call(POLICES_EMBARQUEES, f.family) ? POLICES_EMBARQUEES[f.family] : undefined;
  if (!m) return { ok: false, raison: `famille « ${f.family} » non embarquée · familles disponibles : ${Object.keys(POLICES_EMBARQUEES).join(', ')}` };
  return { ok: true, famille: f.family, metriques: m };
}

/** Métrique d'un caractère · `null` s'il n'est pas couvert (dessiné en .notdef). */
export function metriqueCaractere(m: MetriquesPolice, codePoint: number): MetriqueGlyphe | null {
  return Object.prototype.hasOwnProperty.call(m.glyphes, codePoint) ? m.glyphes[codePoint]! : null;
}
